/**
 * A score as a ring that fills up, with the number in the middle.
 *
 * The ring reads at a glance the way a mark on a page would: green when the class followed
 * you, amber when it partly did, clay when it did not. The number is always shown as text
 * too, so the ring is decoration and never the only way to read the score.
 */
export function ScoreRing({
  value,
  max,
  label,
  size = 'lg',
  onLight = false,
  className,
}: {
  value: number;
  max: number;
  label: string;
  size?: 'lg' | 'sm';
  /** Set when the ring sits on an ivory surface instead of the chalkboard. */
  onLight?: boolean;
  className?: string;
}) {
  const pct = max <= 0 ? 0 : Math.round((value / max) * 100);
  const tone = pct >= 80 ? 'moss' : pct >= 50 ? 'amber' : 'clay';
  const stroke = { moss: '#4C9A78', amber: '#D6A03C', clay: '#C4644B' }[tone];
  const dim = size === 'lg' ? 'h-32 w-32' : 'h-20 w-20';
  return (
    <div className={cn('flex flex-col items-center gap-2', className)}>
      <div className={cn('relative', dim)} role="img" aria-label={`${label}: ${pct}%`}>
        <svg viewBox="0 0 120 120" className="h-full w-full -rotate-90" aria-hidden="true">
          <circle cx="60" cy="60" r="52" fill="none" stroke={onLight ? 'rgba(11,21,33,0.12)' : 'rgba(251,248,241,0.14)'} strokeWidth="10" />
          <circle
            cx="60"
            cy="60"
            r="52"
            fill="none"
            stroke={stroke}
            strokeWidth="10"
            strokeLinecap="round"
            pathLength={100}
            strokeDasharray={`${Math.max(0.01, pct)} 100`}
            className="transition-[stroke-dasharray] duration-700 ease-out"
          />
        </svg>
        <span
          className={cn(
            'absolute inset-0 grid place-items-center font-display font-extrabold',
            onLight ? 'text-ink-strong' : 'text-ink',
            size === 'lg' ? 'text-2xl' : 'text-lg',
          )}
        >
          {pct}%
        </span>
      </div>
      <span className={cn('text-2xs uppercase tracking-[0.12em]', onLight ? 'text-ink-strong/55' : 'text-muted')}>{label}</span>
    </div>
  );
}

/**
 * A little badge on a question showing how hard it is. The class starts on warm-ups and
 * escalates, so a student can see the room getting braver.
 */
const DIFFICULTY_META: Record<Difficulty, { label: string; className: string; title: string }> = {
  warmup: { label: 'Warm-up', className: 'border-right/45 bg-right/10 text-right', title: 'An easier question to check the basics.' },
  core: { label: 'Core', className: 'border-pencil/50 bg-pencil-wash text-pencil-deep', title: 'A question about why it works.' },
  challenge: { label: 'Challenge', className: 'border-wrong/45 bg-wrong/10 text-wrong', title: 'A hard question that pushes the explanation to its limits.' },
};

export function DifficultyChip({ difficulty, className }: { difficulty?: Difficulty; className?: string }) {
  if (!difficulty) return null;
  const meta = DIFFICULTY_META[difficulty];
  return (
    <span className={cn('chip', meta.className, className)} title={meta.title}>
      {meta.label}
    </span>
  );
}

/**
 * Turns the classmates' voices on or off. It is a real toggle backed by the Web Speech API;
 * when the browser cannot speak, the button is disabled and says so rather than pretending.
 */
export function VoiceToggle({
  supported,
  enabled,
  onChange,
  className,
  compact = false,
}: {
  supported: boolean;
  enabled: boolean;
  onChange: (value: boolean) => void;
  className?: string;
  compact?: boolean;
}) {
  const label = !supported ? 'Voice unavailable' : enabled ? 'Voice on' : 'Voice off';
  return (
    <button
      type="button"
      onClick={() => supported && onChange(!enabled)}
      disabled={!supported}
      aria-pressed={enabled}
      title={
        supported
          ? enabled
            ? 'Classmates read their questions aloud. Click to turn sound off.'
            : 'Classmates read their questions aloud. Click to turn sound on.'
          : 'This browser cannot speak text aloud — the questions are shown as text.'
      }
      className={cn(
        'inline-flex items-center gap-2 rounded-full border-2 px-3 py-1.5 text-2xs font-bold uppercase tracking-[0.1em] transition',
        enabled ? 'border-pencil bg-pencil-wash text-pencil-deep' : 'border-line bg-surface text-muted hover:text-ink',
        !supported && 'cursor-not-allowed opacity-50',
        className,
      )}
    >
      {supported && enabled ? <Volume2 className="h-3.5 w-3.5" aria-hidden="true" /> : <VolumeX className="h-3.5 w-3.5" aria-hidden="true" />}
      {!compact && label}
    </button>
  );
}

/** The small mic button used next to text fields. Honest about unsupported browsers. */
export function MicButton({
  supported,
  listening,
  onClick,
  disabled,
  className,
}: {
  supported: boolean;
  listening: boolean;
  onClick: () => void;
  disabled?: boolean;
  className?: string;
}) {
  return (
    <button
      type="button"
      onClick={onClick}
      disabled={!supported || disabled}
      aria-pressed={listening}
      className={cn(
        'inline-flex items-center gap-2 rounded-full border-2 px-3 py-1.5 text-2xs font-bold uppercase tracking-[0.1em] transition',
        listening ? 'border-wrong bg-wrong/12 text-wrong' : 'border-line bg-surface text-ink-soft hover:text-ink',
        (!supported || disabled) && 'cursor-not-allowed opacity-50',
        className,
      )}
      title={supported ? 'Speak your answer instead of typing' : 'Voice input is not available in this browser — type instead'}
    >
      {listening ? (
        <>
          <span className="relative flex h-3 w-3 items-center justify-center" aria-hidden="true">
            <span className="absolute h-3 w-3 animate-pulse-ring rounded-full bg-wrong" />
            <Square className="h-2.5 w-2.5 fill-current" />
          </span>
          Stop
        </>
      ) : (
        <>
          {supported ? <Mic className="h-3.5 w-3.5" aria-hidden="true" /> : <MicOff className="h-3.5 w-3.5" aria-hidden="true" />}
          Speak
        </>
      )}
    </button>
  );
}

const SESSION_STEPS = ['Teach', 'Class quiz', 'Your quiz', 'Report'] as const;
export type SessionStep = (typeof SESSION_STEPS)[number];

/**
 * Where you are in the session: teach, class quiz, your quiz, report. Shown on the working
 * pages so a student always knows how far along the loop they are.
 */
export function SessionSteps({ current, className }: { current: SessionStep; className?: string }) {
  const at = SESSION_STEPS.indexOf(current);
  return (
    <ol className={cn('flex flex-wrap items-center gap-x-2 gap-y-1 text-2xs uppercase tracking-[0.12em]', className)} aria-label="Session steps">
      {SESSION_STEPS.map((label, i) => (
        <li key={label} className="flex items-center gap-2">
          <span
            className={cn(
              'flex items-center gap-1.5',
              i < at ? 'text-right' : i === at ? 'text-pencil-deep' : 'text-muted/70',
            )}
            aria-current={i === at ? 'step' : undefined}
          >
            <span
              className={cn(
                'grid h-4 w-4 place-items-center rounded-full border text-[0.6rem] font-bold',
                i < at ? 'border-right/60 bg-right/20 text-right' : i === at ? 'border-pencil/70 bg-pencil/20 text-pencil-deep' : 'border-line/20',
              )}
            >
              {i < at ? '✓' : i + 1}
            </span>
            {label}
          </span>
          {i < SESSION_STEPS.length - 1 && <span className="h-px w-4 bg-surface/20" aria-hidden="true" />}
        </li>
      ))}
    </ol>
  );
}
