/** A progress rail used by the classroom, quizzes and report. */
export function ProgressRail({ value, max, className }: { value: number; max: number; className?: string }) {
  const percent = max <= 0 ? 0 : Math.min(100, Math.round((value / max) * 100));
  return (
    <div className={cn('h-1.5 w-full overflow-hidden rounded-full bg-surface/12', className)}>
      <div className="h-full rounded-full bg-pencil transition-[width] duration-500 ease-out" style={{ width: `${percent}%` }} />
    </div>
  );
}

