/**
 * Honesty labels.
 *
 * ClassRelay must never present simulated behaviour as real AI, and must always mark
 * AI-generated content. These components are the single place that wording lives.
 */

export function SourceTag({ source, className }: { source: 'ai' | 'demo'; className?: string }) {
  if (source === 'ai') {
    return (
      <span className={cn('chip-amber', className)} title="Generated by the configured AI model.">
        <Sparkles className="h-3 w-3" aria-hidden="true" />
        AI generated
      </span>
    );
  }
  return (
    <span className={cn('chip-slate', className)} title="Produced by the built-in simulation because no AI key is configured.">
      <FlaskConical className="h-3 w-3" aria-hidden="true" />
      Simulated
    </span>
  );
}

